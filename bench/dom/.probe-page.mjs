// Probe (never committed): one bench page's small-op results under a given wiring.
import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { join, extname } from 'node:path';
const dir = new URL('.', import.meta.url).pathname;
const server = createServer((q, r) => { const u = decodeURIComponent(q.url.split('?')[0]); const p = join(dir, u === '/' ? 'index.html' : u); if (!existsSync(p)) return r.writeHead(404), r.end(); r.writeHead(200, { 'content-type': extname(p) === '.html' ? 'text/html' : 'text/javascript' }); r.end(readFileSync(p)); });
await new Promise((res) => server.listen(8099, res));
const b = await chromium.launch({ channel: 'chrome', headless: true });
const p = await b.newPage();
p.on('pageerror', (e) => console.log('pageerror', String(e).slice(0, 300)));
p.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text().slice(0, 200)); });
await p.route('**/bundle.js', (route) => route.fulfill({ body: readFileSync(join(dir, process.argv[2])), contentType: 'text/javascript' }));
await p.goto(`http://localhost:8099/?only=${encodeURIComponent(process.argv[3])}&batch=50&n10=200&ops=update10,select,swap,remove${process.argv[4] ? '&vera=' + process.argv[4] : ''}`, { waitUntil: 'domcontentloaded' });
await p.waitForFunction(() => document.getElementById('status')?.textContent === 'Ready.', null, { timeout: 30000 });
await p.click('#run');
await p.waitForFunction(() => window.__RESULTS__ !== undefined, null, { timeout: 180000 });
const r = await p.evaluate(() => window.__RESULTS__);
console.log(process.argv[3], process.argv[4] ?? 'legacy', 'wiring', await p.evaluate(() => window.__VERA_WIRING__), Object.fromEntries(Object.entries(r).map(([op, v]) => [op, Object.values(v)[0]?.median?.toFixed(3)])));
await b.close(); server.close();
