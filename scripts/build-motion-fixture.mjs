/**
 * Render motion SSR emission through the real pipeline and write the output as a fixture the
 * browser suite paints and hydrates against.
 *
 *   node scripts/build-motion-fixture.mjs          # regenerate
 *   node scripts/build-motion-fixture.mjs --check  # fail if it has drifted (CI)
 *
 * The pipeline here IS the consumer's pipeline: a DOM-hosted page document (jsdom on the server —
 * `renderMotion` runs under any DOM), the same wire array the page would hand `wireDirectives`,
 * and the emitted sheet plus markers serialized out. The browser suite then makes the two claims
 * no jsdom test can: frame 0 PAINTS from the emitted CSS with no vera JavaScript on the page, and
 * wiring the client afterwards re-derives byte-identical identities and takes over the same
 * elements. `--check` is in the gate per the house rule — a committed artifact nothing verifies
 * is how this repo has been bitten twice.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<!doctype html><head></head><body></body>', { pretendToBeVisual: true, url: 'http://localhost/' });
for (const k of ['window', 'document', 'HTMLElement', 'customElements', 'Node', 'Element',
  'DocumentFragment', 'CSSStyleSheet', 'MutationObserver', 'getComputedStyle',
  'IntersectionObserver', 'ResizeObserver']) {
  if (dom.window[k]) globalThis[k] = dom.window[k];
}
globalThis.requestAnimationFrame = dom.window.requestAnimationFrame.bind(dom.window);
globalThis.cancelAnimationFrame = dom.window.cancelAnimationFrame.bind(dom.window);

const { renderMotion, presets } = await import('@verajs/directives/motion');

const check = process.argv.includes('--check');
const target = new URL('../tests/browser/fixtures/motion-ssr.html.js', import.meta.url);
const doc = dom.window.document;

/**
 * The page: the defect's own shape (a fade-up that used to arrive visible and snap), a preset
 * resolving through the same wire array the page uses, an easing-group split, a width band, and
 * an out-of-scope stagger group that must arrive UNMARKED — the client-only path.
 */
doc.body.innerHTML = `
  <div id="fade" data-vd-motion="{ keyframes: { opacity: '0% 0, 100% 1', translate-y: '0% 40px, 100% 0px' } }">fades</div>
  <div id="preset" data-vd-motion="fade-up">preset</div>
  <div id="grouped" data-vd-motion="{ keyframes: { opacity: { frames: '0% 0, 100% 1', ease: 'ease-in' }, translate-y: '0% 80px, 100% 0px' } }">grouped</div>
  <div id="banded" data-vd-motion="{ keyframes: { opacity: '0% 0.6, 100% 0.6; [0-560]: 0% 0.1, 100% 0.1' } }">banded</div>
  <div id="group" data-vd-motion="{ stagger: '10%' }">
    <div id="member" data-vd-motion="{ keyframes: { opacity: '0% 0, 100% 1' } }">member</div>
  </div>`;

const report = renderMotion(doc, { wire: [presets] });
if (report.problems.length) {
  console.error('fixture page must be problem-free:', report.problems);
  process.exit(1);
}

const style = doc.head.querySelector('style[data-vera-sheet]');
const markers = {};
for (const el of doc.querySelectorAll('[data-vd-a]')) {
  markers[el.id] = el.getAttribute('data-vd-a');
}

const contents =
  `/** GENERATED by scripts/build-motion-fixture.mjs — real renderMotion output. Do not edit. */\n` +
  `export const MOTION_CSS = ${JSON.stringify(style.textContent)};\n` +
  `export const MOTION_BODY = ${JSON.stringify(doc.body.innerHTML)};\n` +
  `export const MOTION_MARKERS = ${JSON.stringify(markers)};\n` +
  `export const MOTION_REPORT = ${JSON.stringify({ rendered: report.rendered, skipped: report.skipped, rules: report.rules })};\n`;

if (check) {
  let existing = null;
  try {
    existing = readFileSync(target, 'utf8');
  } catch {
    /* missing counts as drifted */
  }
  if (existing !== contents) {
    console.error('tests/browser/fixtures/motion-ssr.html.js has drifted; run: node scripts/build-motion-fixture.mjs');
    process.exit(1);
  }
  console.log('motion fixture matches the pipeline.');
} else {
  writeFileSync(target, contents);
  console.log(`wrote ${target.pathname} (${report.rendered} rendered, ${report.rules} rules)`);
}
