/**
 * Render the kitchen sink through the real server pipeline and write the pages the browser suite
 * compares.
 *
 *   node scripts/build-kitchen-fixture.mjs          # regenerate
 *   node scripts/build-kitchen-fixture.mjs --check  # fail if it has drifted (CI)
 *
 * Three artifacts, because the suite compares three renderings of one application:
 *
 *   kitchen-ssr.html      the server's markup, no script — what a reader without JS sees
 *   kitchen-hydrate.html  the same markup, with the hydrating renderer adopting it
 *   kitchen-csr.html      an empty shell the plain renderer fills from scratch
 *
 * The browser cannot run `@verajs/ssr` — it is Node-only — so the markup is generated here and
 * committed, exactly as `build-hydration-fixture.mjs` does and for the same reason: hand-writing it
 * would test the test, and an uncommitted artifact would let the browser suite hydrate markup no
 * server emits while passing green.
 */
import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { renderToString } from '@verajs/ssr/vera';

const check = process.argv.includes('--check');
const dir = new URL('../tests/browser/fixtures/', import.meta.url);
const entry = new URL('../examples/kitchen-sink/entry-ssr.js', import.meta.url);

const { html, styles } = await renderToString(entry);

/**
 * `type="module"` and an inline script rather than a file: the fixture has to be self-contained so
 * that regenerating it cannot leave a stale companion behind.
 */
const page = (body, script) => `<!DOCTYPE html>
<!-- GENERATED by scripts/build-kitchen-fixture.mjs — real @verajs/ssr output. Do not edit. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <title>Vera kitchen sink</title>
    <style>${styles}</style>
  </head>
  <body>
${body}
${script}
  </body>
</html>
`;

const boot = (renderer, mode) => `    <script type="module">
      import { start } from '/examples/kitchen-sink/entry-client.js';
      import { render } from '/packages/renderer/dist/development/${renderer}';
      await start(render);
      document.documentElement.dataset.sinkMode = '${mode}';
    </script>`;

const FILES = {
  'kitchen-ssr.html': page(html, ''),
  'kitchen-hydrate.html': page(html, boot('vera-renderer-hydrate.js', 'hydrate')),
  'kitchen-csr.html': page('    <sink-shell></sink-shell>', boot('vera-renderer.js', 'csr')),
};

if (check) {
  let stale = [];
  for (const [name, contents] of Object.entries(FILES)) {
    let committed;
    try {
      committed = readFileSync(new URL(name, dir), 'utf8');
    } catch {
      stale.push(`${name} (missing)`);
      continue;
    }
    if (committed !== contents) stale.push(name);
  }
  if (stale.length) {
    console.error(
      `build-kitchen-fixture: ${stale.join(', ')} no longer match what @verajs/ssr produces.\n` +
        '  The browser suite is therefore comparing against markup no server emits.\n' +
        '  Regenerate and commit:\n\n    node scripts/build-kitchen-fixture.mjs\n'
    );
    process.exit(1);
  }
  console.log('  kitchen fixtures match the current server output');
} else {
  mkdirSync(dir, { recursive: true });
  for (const [name, contents] of Object.entries(FILES)) writeFileSync(new URL(name, dir), contents);
  console.log(`  wrote ${Object.keys(FILES).length} kitchen fixtures (${html.length} B of markup)`);
}
