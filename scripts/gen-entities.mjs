/**
 * Generates `packages/ssr/src/vera/entities.ts`, the HTML Standard's named character references, from the copy of the
 * standard's `entities.json` vendored in `scripts/data/` (its source and license are in `scripts/data/README.md`).
 *
 * The table ships as ONE string literal, in a module of its own, built into a Map by `named-references.ts`, the
 * `@verajs/ssr/named-references` module a server wires; the parser asks it only for a name outside the six it has
 * always known, and a server that does not wire it never loads the table. Its place and shape are what measured
 * cheapest (Node, 2026-11-25, fresh processes):
 *
 *   - a module of its own, holding no function: inside `parse.ts` (at its top, its end, or returned by a function) the
 *     literal doubled garbage collection during a process's first renders, about 20% of a cold styled render, while
 *     in its own module renders are unchanged and importing `@verajs/ssr` costs about 4% more (one more module);
 *   - `name:codepoints,` with each code point in hex (`AElig;:c6,…,nGt;:226b.20d2,…`): only letters, digits and `;:,.`,
 *     so the literal holds no escape. As JSON (some names decode to a tab or a line feed, which JSON escapes) it cost
 *     the import about 1% more; front-coding the sorted names, 17% fewer characters, cost more, not less.
 *
 * The source's sha256 is pinned here: a hand edit to the vendored file, or a new copy of it, fails this script until
 * the pin moves in the same commit, so the table cannot change without a visible diff to both.
 *
 *   node scripts/gen-entities.mjs           # write
 *   node scripts/gen-entities.mjs --check   # fail if the generated file is stale or the source is not the pinned one
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = fileURLToPath(new URL('./data/whatwg-entities.json', import.meta.url));
const TARGET = fileURLToPath(new URL('../packages/ssr/src/vera/entities.ts', import.meta.url));
const SOURCE_SHA256 = 'd741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6';
/** The standard's count when vendored (2,125 names with `;`, 106 legacy names without): a floor on what was read. */
const ENTRIES = 2231;

const bytes = readFileSync(SOURCE);
const sha = createHash('sha256').update(bytes).digest('hex');
if (sha !== SOURCE_SHA256) {
  console.error(`scripts/data/whatwg-entities.json is not the pinned copy (sha256 ${sha}, pinned ${SOURCE_SHA256}).`);
  process.exit(1);
}
const source = JSON.parse(bytes.toString('utf8'));
/** `name:codepoints` per reference, in the standard's order; a name it lists with and without `;` keeps both. */
const entries = [];
let longest = 0;
for (const [reference, { codepoints, characters }] of Object.entries(source)) {
  const valid =
    /^&[A-Za-z][A-Za-z0-9]*;?$/.test(reference) &&
    Array.isArray(codepoints) &&
    codepoints.length > 0 &&
    String.fromCodePoint(...codepoints) === characters;
  if (!valid) {
    console.error(`unexpected entry ${JSON.stringify(reference)}`);
    process.exit(1);
  }
  entries.push(`${reference.slice(1)}:${codepoints.map((code) => code.toString(16)).join('.')}`);
  longest = Math.max(longest, reference.length - 1);
}
if (entries.length !== ENTRIES) {
  console.error(`read ${entries.length} references, expected ${ENTRIES}`);
  process.exit(1);
}
const literal = entries.join(',');
if (!/^[A-Za-z0-9;:,.]+$/.test(literal)) {
  console.error('the table holds a character outside letters, digits and ;:,. and would need an escape');
  process.exit(1);
}

const output = `// Generated by scripts/gen-entities.mjs from scripts/data/whatwg-entities.json (sha256 ${SOURCE_SHA256}). Do not edit.
// Source: https://html.spec.whatwg.org/entities.json, © WHATWG, CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).

/**
 * The HTML Standard's named character references, ${ENTRIES} of them: \`name:codepoints\`, comma-separated, each name
 * without its \`&\` and each code point in hex, \`.\` between two. Names the standard also accepts without a \`;\`
 * (\`amp\`, \`not\`, …) appear twice, with and without it. Read by \`named-references.ts\`; typed \`string\`, not its
 * literal, so the declaration file does not carry a second copy of the table.
 */
export const ENTITIES: string = '${literal}';
/** The longest name, \`;\` included: the decoder tries no prefix longer than this. */
export const LONGEST_ENTITY: number = ${longest};
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(TARGET, 'utf8');
  } catch {}
  if (current !== output) {
    console.error('packages/ssr/src/vera/entities.ts is stale.\nRun: node scripts/gen-entities.mjs');
    process.exit(1);
  }
  console.log(`entities.ts is current (${ENTRIES} references).`);
} else {
  writeFileSync(TARGET, output);
  console.log(`wrote packages/ssr/src/vera/entities.ts (${ENTRIES} references, ${literal.length} characters)`);
}
