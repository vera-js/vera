/**
 * Renders a component through the real server pipeline and writes the markup as a fixture the
 * browser suite can hydrate against.
 *
 * The browser cannot run `@verajs/ssr` (Node-only), and hand-writing the expected markup would
 * test the test rather than the handoff. So the server output is generated here and committed,
 * which also means a change to the serializer shows up as a diff.
 *
 *   node scripts/build-hydration-fixture.mjs
 */
import { writeFileSync } from 'node:fs';
import { renderToString } from '@verajs/ssr/vera';

const { html } = await renderToString(new URL('../tests/fixtures/ssr/hello-ssr.js', import.meta.url));

writeFileSync(
  new URL('../tests/browser/fixtures/hello-ssr.html.js', import.meta.url),
  `/** GENERATED by scripts/build-hydration-fixture.mjs — real @verajs/ssr output. Do not edit. */\n` +
    `export const SERVER_HTML = ${JSON.stringify(html)};\n`
);
console.log('  wrote tests/browser/fixtures/hello-ssr.html.js');
console.log('  markup:', html.slice(0, 140).replace(/\n\s*/g, ' '));
