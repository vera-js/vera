/**
 * **`track` stays small enough for V8 to inline into the store's read trap** (2026-10-29). Every tracked read of every
 * store runs it, and V8 inlines it into `get` only while its bytecode is at most `--max-inlined-bytecode-size` (460 by
 * default). Past that, every read pays a call: a cliff that no code read shows and no correctness test can see (the
 * SSR serializer fell off the same one, +3.6% on every render, `ssr-inlining-budget`).
 *
 * **BOTH bundles are measured, every run**: the minifier rewrites `track`'s statements into expressions (comma sequences,
 * `||` for an `if`), and the bytecode differs — measured 2026-10-29, 447 bytes in development and 454 in production,
 * where the headroom is 6, not 13. Development's is found by name; production renames it, so its name is read from the
 * bundle's source map at `track`'s definition. Limit and lengths come from the V8 this Node runs. The function is driven
 * hot enough to be compiled: readers sharing keys, re-running, stopping.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { TraceMap, allGeneratedPositionsFor } from '@jridgewell/trace-mapping';

const root = new URL('..', import.meta.url);
const DEV = 'packages/core/dist/development/vera.js';
const PROD = 'packages/core/dist/vera.min.js';
/** Where `track` is defined in this tree. */
const TRACK_FILE = 'packages/core/src/services/track.ts';

/** Production's name for `track`: the identifier the source map places at its definition (`TRACK_FILE`). */
const prodName = () => {
  const source = readFileSync(new URL(TRACK_FILE, root), 'utf8').split('\n');
  const line = source.findIndex((l) => l.startsWith('export const track = ')) + 1;
  const map = new TraceMap(JSON.parse(readFileSync(new URL(`${PROD}.map`, root), 'utf8')));
  const file = map.sources.find((s) => s?.endsWith(TRACK_FILE.slice('packages/core/'.length)));
  const [at] = allGeneratedPositionsFor(map, { source: file, line, column: source[line - 1].indexOf('track') });
  const bundle = readFileSync(new URL(PROD, root), 'utf8').split('\n');
  return at === undefined ? undefined : /^[\w$]+/.exec(bundle[at.line - 1].slice(at.column))?.[0];
};

const length = (bundle, name) => {
  const printed = execFileSync(process.execPath, [
    '--print-bytecode', `--print-bytecode-filter=${name}`, '--input-type=module', '-e',
    `const { createStore, effect } = await import('./${bundle}');
     const s = createStore({ a: 0, b: 0, c: 0 });
     const es = [];
     for (let n = 0; n < 200; n++) {
       const e = effect(() => { void s.a; void s[n % 2 ? 'b' : 'c']; }, { owner: {}, timing: 'sync' });
       e.run();
       es.push(e);
       s.a++;
       if (es.length > 8) es.shift().stop();
     }`,
  ], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const found = [...printed.matchAll(new RegExp(`generated bytecode for function: ${name.replace(/\$/g, '\\$')} [\\s\\S]*?Bytecode length: (\\d+)`, 'g'))];
  /** Exactly one function of that name: a short production name shared by two functions would measure either. */
  assert.equal(found.length, 1, `CONTROL: exactly one function named ${name} in ${bundle} (found ${found.length})`);
  return Number(found[0][1]);
};

test("track's bytecode fits V8's inlining budget, in both bundles", (t) => {
  const limit = Number(/--max-inlined-bytecode-size=(\d+)/.exec(execFileSync(process.execPath, ['--v8-options'], { encoding: 'utf8' }))?.[1]);
  assert.ok(limit > 0, `CONTROL: read the inlining limit from this V8 (${limit})`);
  const name = prodName();
  assert.ok(name, "CONTROL: production's name for track read from its source map");
  for (const [bundle, fn] of [[DEV, 'track'], [PROD, name]]) {
    const bytes = length(bundle, fn);
    /** A parse that reads nothing must go red, not pass: the function is ~450 bytes; anything under 100 is a misread. */
    assert.ok(bytes > 100, `CONTROL: read track's bytecode length from V8 in ${bundle} (${bytes})`);
    /** The headroom, every run: a reviewer sees it shrink before the next change falls off the cliff. */
    t.diagnostic(`track (${bundle}, as ${fn}): ${bytes} of ${limit} bytes of bytecode — ${limit - bytes} to spare`);
    assert.ok(bytes <= limit, `track in ${bundle} is ${bytes} bytes of bytecode, over V8's inlining limit of ${limit}: move a rarely-run piece (the sweep, a divergence) out of line — see this file`);
  }
});
